#!/usr/bin/env python3
"""Build/check the exact Package 03 atomic migration, without accessing any database."""
import hashlib
import json
import re
import sys
from pathlib import Path
root=Path(__file__).resolve().parents[1]
test=(root/'tests/test_p03_full_schema.mjs').read_text()
file_list=re.search(r"const files=(\[[^\n]+\]);",test)
if not file_list:
    raise SystemExit('Migration order missing from the integration suite')
files=json.loads(file_list[1].replace("'",'"'))
parts=["-- Generated by tools/build_p03_release.py. Apply this bundle ONCE, not the individual files as well.\nBEGIN;\nSET LOCAL lock_timeout='5s';\nSET LOCAL statement_timeout='120s';\nSELECT pg_advisory_xact_lock(hashtextextended('sri_p03_release_integral_20261125',0));\n"]
# Hash the original column set inside the same transaction and hold data stable.
# No operational payload leaves PostgreSQL or is persisted by this check.
parts.append(r'''
CREATE TEMP TABLE sri_p03_preflight_integrity(relation_name text PRIMARY KEY,original_columns text[],row_count bigint,content_hash text) ON COMMIT DROP;
DO $integrity_before$
DECLARE item record; relation_name text; columns_before text[]; total bigint; digest text;
BEGIN
 FOR item IN SELECT schemaname,tablename FROM pg_tables WHERE schemaname IN ('public','private') ORDER BY schemaname,tablename LOOP
  relation_name:=format('%I.%I',item.schemaname,item.tablename);
  EXECUTE 'LOCK TABLE '||relation_name||' IN SHARE ROW EXCLUSIVE MODE';
  SELECT array_agg(attname::text ORDER BY attnum) INTO columns_before FROM pg_attribute WHERE attrelid=relation_name::regclass AND attnum>0 AND NOT attisdropped;
  EXECUTE 'SELECT count(*),md5(coalesce(jsonb_agg(to_jsonb(t) ORDER BY to_jsonb(t)::text)::text,''[]'')) FROM '||relation_name||' t' INTO total,digest;
  INSERT INTO sri_p03_preflight_integrity VALUES(relation_name,columns_before,total,digest);
 END LOOP;
END $integrity_before$;
''')
manifest={'backlog':'docs/pacote-03-consulta@7fc125e44be85cfe1eb6d36ace084e851e3c0c16:docs/backlog-pacote-03.md','migrations':[]}
for name in files:
    path='sql/'+name
    source=(root/path).read_text()
    manifest['migrations'].append({'path':path,'sha256':hashlib.sha256(source.encode()).hexdigest()})
    body=re.sub(r'^\s*(?:BEGIN|COMMIT);\s*$', '',source,flags=re.MULTILINE)
    parts.append('\n-- SOURCE '+path+'\n'+body.strip()+'\n')
parts.append(r'''
DO $integrity_after$
DECLARE item record; total bigint; digest text;
BEGIN
 FOR item IN SELECT * FROM sri_p03_preflight_integrity LOOP
  EXECUTE 'SELECT count(*),md5(coalesce(jsonb_agg(original ORDER BY original::text)::text,''[]'')) FROM (SELECT (SELECT jsonb_object_agg(key,value) FROM jsonb_each(to_jsonb(t)) WHERE key=ANY($1)) original FROM '||item.relation_name||' t) rows'
  INTO total,digest USING item.original_columns;
  IF total IS DISTINCT FROM item.row_count OR digest IS DISTINCT FROM item.content_hash THEN
   RAISE EXCEPTION 'Integrity check failed for %. Transaction rolled back.',item.relation_name;
  END IF;
 END LOOP;
END $integrity_after$;
COMMIT;
''')
bundle=''.join(parts)
manifest['bundle']='sql/2026-11-25_sri_p03_release_integral.sql'
manifest['bundle_sha256']=hashlib.sha256(bundle.encode()).hexdigest()
outputs={root/manifest['bundle']:bundle,root/'docs/PACOTE03-MANIFESTO-20261125.json':json.dumps(manifest,ensure_ascii=False,indent=2)+'\n'}
if '--check' in sys.argv:
    for path,content in outputs.items():
        if not path.exists() or path.read_text()!=content:
            raise SystemExit('Release artifact out of date: '+str(path))
else:
    for path,content in outputs.items():path.write_text(content)
print('PASS: pacote atômico confere com '+str(len(files))+' migrações e respectivos SHA-256.')
