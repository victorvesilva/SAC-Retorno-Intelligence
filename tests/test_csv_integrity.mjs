import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const html=fs.readFileSync(new URL('../index.html',import.meta.url),'utf8');
const start=html.indexOf('/* SRI CSV — correcoes auditaveis:');
const end=html.indexOf('/* v1.9.5: leitura de todas as ocorrências;',start);
assert.ok(start>=0&&end>start,'Guardas CSV não foram incluídas no módulo de importação');
const context=vm.createContext({});
new vm.Script(html.slice(start,end)).runInContext(context);
const {sriNormalizeSacFields,sriInspectAtivoFields}=context;
assert.equal(typeof sriNormalizeSacFields,'function');
assert.equal(typeof sriInspectAtivoFields,'function');
const normal=Array(37).fill('');
assert.equal(sriNormalizeSacFields(normal).invalid,false);
const damaged=Array(38).fill('');
damaged[20]='Procedimento';damaged[21]='Informação adicional';damaged[22]='789';
damaged[36]='N';damaged[37]='S';
const repaired=sriNormalizeSacFields(damaged);
assert.equal(repaired.invalid,false);
assert.equal(repaired.repaired,true);
assert.equal(repaired.fields.length,37);
assert.equal(repaired.fields[20],'Procedimento;Informação adicional');
assert.equal(repaired.fields[21],'789');
assert.equal(repaired.fields[35],'N');
assert.equal(repaired.fields[36],'S');
assert.equal(sriNormalizeSacFields(Array(38).fill('')).invalid,true,'Desalinhamentos não reconhecidos devem ser rejeitados');
const ativo=Array(19).fill('');
ativo[0]='1234567890';ativo[1]='12';ativo[2]='12';ativo[4]='RETORNO';
assert.equal(sriInspectAtivoFields(ativo).valid,true);
assert.equal(sriInspectAtivoFields([...ativo,'texto livre']).extra,1);
assert.equal(sriInspectAtivoFields(ativo.slice(0,14)).invalid,true);
assert.equal(sriInspectAtivoFields(['observação sem protocolo']).valid,false);
assert.equal(sriInspectAtivoFields(['1234567890','incorreto','12',...Array(16).fill('')]).invalid,true);
assert.match(html,/ativoTailWarnings:a\.extraTailWarnings/);
assert.match(html,/sacSemicolonRepairs:s\.semicolonRepairs/);
console.log('PASS: SAC realinhado com segurança, ATIVO validado por colunas estruturadas e alertas ligados à interface.');
